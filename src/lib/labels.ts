/** Unknown action names still read as words ("Platform invoice issue"), never a raw code. */
const words = (k: string) => k.replace(/[._]+/g, " ").replace(/^./, (c) => c.toUpperCase());
export const actionLabel = (k: string, locale: string) => {
  const hit = ACTIONS[k];
  if (hit) return locale === "ar" ? hit.ar : hit.en;
  return words(k);
};
