export function arabicError(message: string): string {
  if (!message) return message;
  const exact = EXACT[message];
  if (exact) return exact;
  for (const [re, fn] of PATTERNS) {
    const m = message.match(re);
    if (m) return fn(...m.slice(1));
  }
  return message;
}

/** True when the page is in Arabic (set on <html lang> by the root layout). */
export function pageIsArabic() {
  return typeof document !== "undefined" && (document.documentElement.lang || "ar").startsWith("ar");
}
